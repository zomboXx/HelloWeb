package com.example.jdbc.data;

import com.zaxxer.hikari.HikariConfig;
import com.zaxxer.hikari.HikariDataSource;
import jakarta.servlet.ServletContextEvent;
import jakarta.servlet.ServletContextListener;
import jakarta.servlet.annotation.WebListener;

import java.sql.Connection;
import java.sql.Driver;
import java.sql.DriverManager;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.sql.Statement;

@WebListener
public class Database implements ServletContextListener {
    private static final String DATA_SOURCE_KEY = "dataSource";

    @Override
    public void contextInitialized(ServletContextEvent event) {
        HikariConfig config = new HikariConfig();
        config.setPoolName("jdbc-mvc-pool");
        config.setDriverClassName("org.h2.Driver");
        config.setJdbcUrl("jdbc:h2:mem:course;MODE=MySQL;NON_KEYWORDS=USER;DB_CLOSE_DELAY=-1");
        config.setUsername("sa");
        config.setPassword("");
        config.setMaximumPoolSize(5);
        config.setMinimumIdle(1);

        HikariDataSource dataSource = new HikariDataSource(config);
        try {
            initializeSchema(dataSource);
            event.getServletContext().setAttribute(DATA_SOURCE_KEY, dataSource);
        } catch (SQLException e) {
            dataSource.close();
            throw new IllegalStateException("Cannot initialize the demo database", e);
        }
    }

    @Override
    public void contextDestroyed(ServletContextEvent event) {
        Object value = event.getServletContext().getAttribute(DATA_SOURCE_KEY);
        if (value instanceof HikariDataSource dataSource) {
            dataSource.close();
        }
        ClassLoader webAppLoader = getClass().getClassLoader();
        for (Driver driver : java.util.Collections.list(DriverManager.getDrivers())) {
            if (driver.getClass().getClassLoader() == webAppLoader) {
                try {
                    DriverManager.deregisterDriver(driver);
                } catch (SQLException e) {
                    event.getServletContext().log("Cannot unregister JDBC driver", e);
                }
            }
        }
    }

    public static HikariDataSource from(jakarta.servlet.ServletContext context) {
        return (HikariDataSource) context.getAttribute(DATA_SOURCE_KEY);
    }

    private static void initializeSchema(HikariDataSource dataSource) throws SQLException {
        try (Connection connection = dataSource.getConnection();
             Statement statement = connection.createStatement()) {
            statement.executeUpdate("""
                CREATE TABLE IF NOT EXISTS User (
                    UserID INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    Email VARCHAR(255) NOT NULL UNIQUE,
                    FirstName VARCHAR(100) NOT NULL,
                    LastName VARCHAR(100) NOT NULL
                )
                """);

            try (ResultSet rows = statement.executeQuery("SELECT COUNT(*) FROM User")) {
                rows.next();
                if (rows.getInt(1) != 0) {
                    return;
                }
            }

            try (PreparedStatement insert = connection.prepareStatement(
                    "INSERT INTO User (Email, FirstName, LastName) VALUES (?, ?, ?)")) {
                addSample(insert, "jsmith@gmail.com", "John", "Smith");
                addSample(insert, "andi@murach.com", "Andrea", "Steelman");
                addSample(insert, "joel.murach@yahoo.com", "Joel", "Murach");
                insert.executeBatch();
            }
        }
    }

    private static void addSample(PreparedStatement insert, String email, String first, String last)
            throws SQLException {
        insert.setString(1, email);
        insert.setString(2, first);
        insert.setString(3, last);
        insert.addBatch();
    }
}
